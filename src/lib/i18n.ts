export const dictionaries: Record<Lang, Dict> = { ru, kz };

export function isLang(value: unknown): value is Lang {
  return value === "ru" || value === "kz";
}

export function productCount(n: number, lang: Lang) {
  if (lang === "kz") return `${n} тауар`;
  const mod10 = n % 10;
  const mod100 = n % 100;
  const word =
    mod10 === 1 && mod100 !== 11 ? "товар" : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? "товара" : "товаров";
  return `${n} ${word}`;
}

export function categoryName(c: { nameRu: string | null; nameKz: string | null }, lang: Lang) {
  return (lang === "kz" ? c.nameKz : c.nameRu) || c.nameRu || "";
}
